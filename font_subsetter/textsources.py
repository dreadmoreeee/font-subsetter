"""Text sources that need no browser: local HTML files and character files."""
from __future__ import annotations

import re
from html.parser import HTMLParser

# Attributes whose value is shown to users (tooltips, alt text when an image
# fails, placeholders, labels read by screen readers and shown by some UIs).
TEXT_ATTRS = ("alt", "title", "aria-label", "placeholder")
# Elements whose text never renders with a web font.
SKIP_TAGS = {"script", "style", "noscript", "template", "head", "title"}
_VALUE_INPUTS = {"button", "submit", "reset", "text", "search", "email", "url", "tel", "number", ""}
_VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta",
         "source", "track", "wbr"}

# CSS "content" strings, e.g. content: "\2192" or content: '> '.
_CONTENT = re.compile(r"content\s*:\s*((?:\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)*'|[^;}\"'])+)", re.I | re.S)
_CSS_STRING = re.compile(r"\"((?:[^\"\\]|\\.)*)\"|'((?:[^'\\]|\\.)*)'", re.S)
_CSS_ESCAPE = re.compile(r"\\([0-9a-fA-F]{1,6})\s?|\\(.)", re.S)


def _unescape_css(s: str) -> str:
    def repl(m):
        if m.group(1):
            cp = int(m.group(1), 16)
            return chr(cp) if 0 < cp <= 0x10FFFF else ""
        return "" if m.group(2) == "\n" else m.group(2)
    return _CSS_ESCAPE.sub(repl, s)


def css_content_text(css: str) -> str:
    """Characters generated by `content:` declarations in a stylesheet."""
    out = []
    for decl in _CONTENT.finditer(css):
        for m in _CSS_STRING.finditer(decl.group(1)):
            out.append(_unescape_css(m.group(1) if m.group(1) is not None else m.group(2)))
    return "".join(out)


class _Extractor(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.css: list[str] = []
        self._stack: list[str] = []

    def _skipping(self) -> bool:
        return any(t in SKIP_TAGS for t in self._stack)

    def handle_starttag(self, tag, attrs):
        a = {k: (v or "") for k, v in attrs}
        if "style" in a:
            self.css.append("x{" + a["style"] + "}")
        if not self._skipping() and tag != "html":
            for name in TEXT_ATTRS:
                if a.get(name):
                    self.parts.append(a[name])
            if tag == "input" and a.get("type", "").lower() in _VALUE_INPUTS and a.get("value"):
                self.parts.append(a["value"])
        if tag not in _VOID:
            self._stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in _VOID and self._stack and self._stack[-1] == tag:
            self._stack.pop()

    def handle_endtag(self, tag):
        if tag in self._stack:
            while self._stack:
                if self._stack.pop() == tag:
                    break

    def handle_data(self, data):
        if self._stack and self._stack[-1] == "style":
            self.css.append(data)
        elif not self._skipping():
            self.parts.append(data)


def html_text(html: str) -> str:
    """Visible text of an HTML document: text nodes, alt/title/aria-label/
    placeholder/value attributes and strings from CSS `content:` in <style>
    blocks and style attributes. Scripts are not run; use a URL (rendered in
    Chromium) when the page builds its text with JavaScript."""
    p = _Extractor()
    p.feed(html)
    p.close()
    return "".join(p.parts) + css_content_text("\n".join(p.css))


def read_text_file(path: str) -> str:
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def codepoints_of(text: str) -> set[int]:
    """Code points worth putting in a font: no control characters. A space is
    always included because every text needs one."""
    cps = {ord(c) for c in text if ord(c) >= 0x20 and not 0x7F <= ord(c) < 0xA0}
    cps.add(0x20)
    return cps


def add_case_variants(cps: set[int]) -> set[int]:
    """Upper and lower case of every letter (for text-transform added later)."""
    out = set(cps)
    for cp in cps:
        ch = chr(cp)
        for v in (ch.upper(), ch.lower()):
            if len(v) == 1:
                out.add(ord(v))
    return out
